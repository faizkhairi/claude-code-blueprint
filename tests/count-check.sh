#!/bin/bash
# Verifies every published component count against the filesystem.
# Run: bash tests/count-check.sh
#
# WHY THIS EXISTS
#
# Counts like "12 agents" are duplicated across the README, three translations, the
# docs, AGENTS.md, and the HTML card sources. When a component is added, some copies
# get updated and others do not. At the time this guard was written the repo shipped
# "11 agents" in AGENTS.md and README.md, "18 skills" in AGENTS.md, "11" in all three
# translated READMEs, and "8 lifecycle events" in SETTINGS-GUIDE.md, while the
# filesystem held 12 agents, 19 skills, and 9 events.
#
# HOW IT WORKS, AND WHY IT IS A REGISTRY RATHER THAN A SWEEP
#
# The obvious design is to scan all prose for "<digit> <category>" and compare. That
# was tried first and measured: it produced 7 false positives and missed 4 real bugs.
#
#   False positives, all legitimate text that is NOT a category total:
#     docs/PRESETS.md      "Add 4 hooks + 2 agents"      per-preset delta
#     README.md, SETUP.md  "CLAUDE.md + 2 hooks"         adoption-path row
#     slide-5.html         three preset cards on one line, digit and label in
#                          separate <div>s, so "nearest number" is a coin flip
#   Misses, all real bugs no <digit> <noun> regex can reach:
#     AGENTS.md            "11 reusable agent templates" (adjective splits the pair)
#     README.md            "We give you **11**"          (category is in the prior clause)
#     i18n ja/ko/zh        "11個" / "11개" / "11 个"      (CJK counter, category in
#                                                          another clause and script)
#
# SETUP.md settles it: "+ 4 more hooks, 2 agents" and "+ all 12 agents, 19 skills"
# sit one line apart in the SAME table. Totals and deltas are not lexically separable.
#
# So instead of excluding what is wrong, this registers what is right: an explicit
# (file, anchor, expected) binding per published total. Expected values are always
# derived from the filesystem, never hardcoded, so adding a 13th agent updates every
# expectation automatically and the guard reports which documents still say 12.
#
# Trade-off, stated plainly: a registry cannot catch a count introduced in a brand-new
# location tomorrow, which a sweep theoretically could. But the sweep's measured
# behaviour was 11 wrong verdicts out of 13, so its theoretical reach bought nothing.
# When you add a new published count, add a binding here. MISSING_ANCHOR failures are
# how the guard tells you a document was reworded out from under it.
#
# WHY BINDINGS ARE PER-LINE AND NOT PER-FILE
#
# A file is not a trust boundary. i18n/README.ko.md states OUR agent count on line 107
# and Project-AI-MemoryCore's "11 feature extensions" on line 303, in the same CJK
# counter form. A file-level rule would either miss the bug or corrupt a third-party
# credit. Anchors bind to surrounding text, so they cannot drift onto the wrong line.
#
# SCOPE
#
# Published counts are only ever read from the .md and .html files named in the
# bindings below. Ground truth is read separately, by counting files under agents/,
# skills/, hooks/ and rules/ and by parsing docs/WHY.md and the settings template.
#
# No .sh file is ever scanned for a count, so this script's own text cannot match
# its own patterns, and the notes above can name forbidden phrasings in plain
# language without flagging themselves.
#
# KNOWN LIMITATION
#
# assets/*.png and walkthrough.gif are generated by hand from the .html sources. Only
# the HTML is checked here, so a stale rendered image whose source is correct will NOT
# be caught. Regenerate the images when a count changes.

PASS=0
FAIL=0

pass() { echo "  PASS: $1"; PASS=$((PASS + 1)); }
fail() { echo "  FAIL: $1"; FAIL=$((FAIL + 1)); }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 1

echo "=== Component Count Check ==="
echo "Directory: $ROOT"
echo ""

# --- Ground truth, derived from the filesystem ------------------------------

N_AGENTS=$(find agents -maxdepth 1 -name '*.md' ! -name 'README.md' | wc -l | tr -d ' ')
N_SKILLS=$(find skills -mindepth 1 -maxdepth 1 -type d ! -name '.*' | wc -l | tr -d ' ')
N_HOOKS=$(find hooks -maxdepth 1 -name '*.sh' ! -name 'test-hooks.sh' | wc -l | tr -d ' ')
N_RULES=$(find rules -maxdepth 1 -name '*.md' ! -name 'README.md' | wc -l | tr -d ' ')

# The hook total splits into lifecycle hooks (wired in settings) and utility scripts
# (run by hand). hooks/README.md publishes the split, so derive both addends, not
# just the total: "14 + 1" also sums to 15 while being wrong about both halves.
N_UTILITY=$(find hooks -maxdepth 1 \( -name 'verify-mcp-sync.sh' -o -name 'status-line.sh' \) | wc -l | tr -d ' ')
N_LIFECYCLE=$((N_HOOKS - N_UTILITY))
N_STORIES=$(grep -c '^### ' docs/WHY.md | tr -d ' ')

# Lifecycle events = distinct keys under "hooks" in the settings template. Counted
# with grep rather than a JSON parser so the guard has no python/jq dependency in CI.
N_EVENTS=$(sed -n '/"hooks"[[:space:]]*:[[:space:]]*{/,/^  }/p' examples/settings-template.json \
  | grep -cE '^    "[A-Za-z]+"[[:space:]]*:' | tr -d ' ')

# Model tiers, read from each agent's frontmatter.
N_OPUS=$(grep -l '^model: opus' agents/*.md 2>/dev/null | wc -l | tr -d ' ')
N_SONNET=$(grep -l '^model: sonnet' agents/*.md 2>/dev/null | wc -l | tr -d ' ')
N_HAIKU=$(grep -l '^model: haiku' agents/*.md 2>/dev/null | wc -l | tr -d ' ')

echo "Ground truth from filesystem:"
echo "  agents=$N_AGENTS  skills=$N_SKILLS  hooks=$N_HOOKS  rules=$N_RULES"
echo "  battle stories=$N_STORIES  lifecycle events=$N_EVENTS"
echo "  model tiers: opus=$N_OPUS sonnet=$N_SONNET haiku=$N_HAIKU"
echo ""

# --- Binding primitive ------------------------------------------------------
#
# bind <file> <anchor-regex> <expected> <label>
#
# The anchor must match exactly one line and must capture the number in a group.
# Where an anchor has alternations (the same sentence written with different quote
# characters per locale), the first non-empty group wins, since only the branch
# that matched contributes a value.
#
# Three distinct outcomes, deliberately kept apart:
#   MISSING  the anchor matched nothing. The document was reworded; update this
#            registry. Silence here would mean the guard quietly stopped checking.
#   AMBIGUOUS the anchor matched more than one line. The binding is too loose to
#            be trusted, so it fails rather than guessing which line was meant.
#   MISMATCH the number is stale. The real finding.

bind() {
  local file="$1" anchor="$2" expected="$3" label="$4"
  if [ ! -f "$file" ]; then
    fail "$label: $file does not exist"
    return
  fi
  local hits
  hits=$(grep -nE "$anchor" "$file" 2>/dev/null)
  local n_hits
  n_hits=$(printf '%s' "$hits" | grep -c . )
  if [ "$n_hits" -eq 0 ]; then
    fail "$label: MISSING_ANCHOR in $file (reworded? update tests/count-check.sh)"
    return
  fi
  if [ "$n_hits" -gt 1 ]; then
    fail "$label: AMBIGUOUS, anchor matched $n_hits lines in $file"
    return
  fi
  local ln text actual
  ln=${hits%%:*}
  text=${hits#*:}
  # Capture with bash's own regex engine, not sed. Anchors contain "/" (`agents/`,
  # `(agents/)`), which collides with any sed s/// delimiter, and a trailing .* in a
  # sed expression swallows the rest of the line into the capture. =~ has no
  # delimiter and returns the group verbatim.
  actual=""
  if [[ $text =~ $anchor ]]; then
    local g
    for g in "${BASH_REMATCH[@]:1}"; do
      if [ -n "$g" ]; then actual="$g"; break; fi
    done
  fi
  if [ -z "$actual" ]; then
    fail "$label: $file:$ln matched but captured no number (bad anchor)"
  elif [ "$actual" = "$expected" ]; then
    pass "$label ($file:$ln) = $actual"
  else
    fail "$label: $file:$ln says $actual, expected $expected"
  fi
}

# ============================================================================
# AGENTS.md, the repo map an AI assistant reads first
# ============================================================================
echo "--- AGENTS.md repo map ---"
bind AGENTS.md '\| `agents/` \| ([0-9]+) reusable agent'  "$N_AGENTS" "agents/ row"
bind AGENTS.md '\| `skills/` \| ([0-9]+) reusable skill'  "$N_SKILLS" "skills/ row"
bind AGENTS.md '\| `hooks/` \| ([0-9]+) hook scripts'     "$N_HOOKS"  "hooks/ row"
bind AGENTS.md '\| `rules/` \| ([0-9]+) example rule'     "$N_RULES"  "rules/ row"

# ============================================================================
# The headline banner, copied verbatim into all three translations
# ============================================================================
echo ""
echo "--- Headline banner ---"
for f in README.md i18n/README.ja.md i18n/README.ko.md i18n/README.zh.md; do
  bind "$f" '^\*\*([0-9]+) agents\*\*'                        "$N_AGENTS" "$f banner agents"
  bind "$f" '^\*\*[0-9]+ agents\*\*.*\*\*([0-9]+) skills\*\*' "$N_SKILLS" "$f banner skills"
  bind "$f" '^\*\*[0-9]+ agents\*\*.*\*\*([0-9]+) hooks\*\*'  "$N_HOOKS"  "$f banner hooks"
  bind "$f" '^\*\*[0-9]+ agents\*\*.*\*\*([0-9]+) rules\*\*'  "$N_RULES"  "$f banner rules"
done

# ============================================================================
# The "what makes this different" comparison line.
#
# English states a bare "**11**" with the category in the preceding clause. The
# three translations use a CJK counter. Each is anchored on its own surrounding
# words, which is what keeps these bindings off i18n line 303, where the same
# counter form describes Project-AI-MemoryCore's feature extensions, not ours.
# ============================================================================
echo ""
echo "--- Agent-count comparison line ---"
bind README.md        'We give you \*\*([0-9]+)\*\*'   "$N_AGENTS" "README comparison"
bind i18n/README.ja.md '私たちは \*\*([0-9]+)個\*\* だけを提供' "$N_AGENTS" "ja comparison"
bind i18n/README.ko.md '우리는 \*\*([0-9]+)개\*\*를 제공'       "$N_AGENTS" "ko comparison"
bind i18n/README.zh.md '我们给你 \*\*([0-9]+) 个\*\*'           "$N_AGENTS" "zh comparison"

# ============================================================================
# Docs that state a total in running prose
# ============================================================================
echo ""
echo "--- Docs prose totals ---"
bind docs/SETTINGS-GUIDE.md 'configures hooks across ([0-9]+) lifecycle events' "$N_EVENTS" "SETTINGS-GUIDE events"
bind hooks/README.md        'covering ([0-9]+) lifecycle events'                "$N_EVENTS" "hooks/README events"
bind FAQ.md                 '^### "([0-9]+) agents, [0-9]+ skills'              "$N_AGENTS" "FAQ headline agents"
bind FAQ.md                 '^### "[0-9]+ agents, ([0-9]+) skills'              "$N_SKILLS" "FAQ headline skills"
bind FAQ.md                 '^### "[0-9]+ agents, [0-9]+ skills, ([0-9]+) hooks' "$N_HOOKS" "FAQ headline hooks"
bind FAQ.md                 '^### "[0-9]+ agents, [0-9]+ skills, [0-9]+ hooks, ([0-9]+) rules' "$N_RULES" "FAQ headline rules"
bind GETTING-STARTED.md     '\[([0-9]+) agents\]\(agents/\)'                    "$N_AGENTS" "GETTING-STARTED agents link"
bind SETUP.md               '\+ all ([0-9]+) agents'                            "$N_AGENTS" "SETUP full-preset agents"
bind SETUP.md               '\+ all [0-9]+ agents, ([0-9]+) skills'             "$N_SKILLS" "SETUP full-preset skills"
bind SETUP.md               '\+ all [0-9]+ agents, [0-9]+ skills, ([0-9]+) rules' "$N_RULES" "SETUP full-preset rules"

# ============================================================================
# The hooks/README.md sum. This line states "13 + 2" and never the digit 15, so
# no value binding can validate it. Check each addend against its own derived
# value, not merely that the two sum correctly: "14 + 1" also totals 15 while
# misstating both halves.
# ============================================================================
echo ""
echo "--- hooks/README.md sum arithmetic ---"
SUM_LINE=$(grep -oE '^[0-9]+ lifecycle hooks \+ [0-9]+ utility scripts' hooks/README.md)
N_SUM_LINES=$(printf '%s' "$SUM_LINE" | grep -c .)
if [ "$N_SUM_LINES" -gt 1 ]; then
  # Same rule as bind() and card(): more than one match is a document the guard
  # cannot reason about, so fail rather than pick one. Without this the two
  # values below hold newline-joined text and bash reports "integer expression
  # expected", which reads as a broken guard rather than a broken document.
  fail "hooks/README.md sum line: AMBIGUOUS, anchor matched $N_SUM_LINES lines"
elif [ -n "$SUM_LINE" ]; then
  a=$(printf '%s' "$SUM_LINE" | grep -oE '^[0-9]+')
  b=$(printf '%s' "$SUM_LINE" | grep -oE '\+ [0-9]+' | grep -oE '[0-9]+')
  if [ "$a" -ne "$N_LIFECYCLE" ]; then
    fail "hooks/README.md says $a lifecycle hooks, expected $N_LIFECYCLE"
  elif [ "$b" -ne "$N_UTILITY" ]; then
    fail "hooks/README.md says $b utility scripts, expected $N_UTILITY"
  elif [ "$((a + b))" -ne "$N_HOOKS" ]; then
    fail "hooks/README.md: $a + $b = $((a + b)), expected $N_HOOKS"
  else
    pass "hooks/README.md: $a + $b = $N_HOOKS"
  fi
else
  fail "hooks/README.md sum line MISSING_ANCHOR (reworded?)"
fi

# ============================================================================
# The "not counted in the total" explanations.
#
# README.md:179 and its three translations quote the hook total while explaining
# what is EXCLUDED from it. The value is checked like any other, but the wording
# is load-bearing: never auto-rewrite these lines, edit them by hand.
# ============================================================================
echo ""
echo "--- Exclusion-explanation lines (value checked, wording load-bearing) ---"
for f in README.md i18n/README.ja.md i18n/README.ko.md i18n/README.zh.md; do
  # Quote style differs by locale: ASCII in en/ko, full-width in ja/zh.
  bind "$f" '"([0-9]+) hooks"|“([0-9]+) hooks”|「([0-9]+) hooks」' "$N_HOOKS" "$f hook-total mention"
done

# ============================================================================
# Model tier split
# ============================================================================
echo ""
echo "--- Model tier split ---"
# Only the Sonnet row states a number. The Opus and Haiku rows name their single
# agent instead (project-architect, docs-writer), so there is nothing to bind; the
# sum check below is what catches a tier drifting out of balance.
bind docs/ARCHITECTURE.md '^\| \*\*Sonnet\*\*.*\| ([0-9]+) agents \(' "$N_SONNET" "ARCHITECTURE Sonnet tier"
bind docs/WHY.md          '^- \*\*Sonnet\*\*:.*\(([0-9]+) agents\)'    "$N_SONNET" "WHY Sonnet tier"
if [ "$((N_OPUS + N_SONNET + N_HAIKU))" -eq "$N_AGENTS" ]; then
  pass "model tiers sum to $N_AGENTS ($N_OPUS opus + $N_SONNET sonnet + $N_HAIKU haiku)"
else
  fail "model tiers sum to $((N_OPUS + N_SONNET + N_HAIKU)), expected $N_AGENTS"
fi

# ============================================================================
# Asset HTML.
#
# Nothing in CI touches assets/ today, and the CHANGELOG records these card
# counts drifting for an entire release cycle. Cards put the number and its
# label in sibling <div>s, so bind on the pair rather than on line proximity:
# slide-5.html has three preset cards on a single line.
#
# slide-5.html itself is deliberately NOT bound here. Its cards show per-preset
# FILE totals (4 / 10 / 20 / 55), which are sums over the installer's arrays and
# not component counts; tests/install-matrix.sh is what exercises those.
# ============================================================================
echo ""
echo "--- Asset HTML card counts ---"
card() {
  local file="$1" label="$2" expected="$3"
  if [ ! -f "$file" ]; then
    fail "$label: $file does not exist"
    return
  fi
  # The count div and its label div are siblings, but all three card layouts differ:
  # card-overview.html puts them on consecutive lines, slide-2.html puts several
  # whole cards on one line, and card-social-preview.html wraps the label in an
  # extra element so the two are not adjacent. Flatten the file to a single stream,
  # then allow a bounded run of non-digit markup between the count and its label.
  # The run must not contain another count div, so a neighbouring card on the same
  # line can never be picked up by mistake.
  local matches n_matches n
  matches=$(tr '\n' ' ' < "$file" \
      | grep -oE "<div class=\"(item-)?count\">[0-9]+</div>([^0-9]{0,80})<div class=\"(item-)?label\">$label<" \
      | grep -oE '^<div class="(item-)?count">[0-9]+' | grep -oE '[0-9]+$')
  n_matches=$(printf '%s' "$matches" | grep -c .)
  # Same rule as bind(): two cards carrying the same label means the document is
  # half-edited, and silently taking the first would make the verdict depend on
  # document order. Fail instead of guessing which one was meant.
  if [ "$n_matches" -gt 1 ]; then
    fail "$file $label: AMBIGUOUS, $n_matches cards carry this label ($(printf '%s' "$matches" | tr '\n' ' '))"
    return
  fi
  n=$(printf '%s' "$matches" | head -1)
  if [ -z "$n" ]; then
    fail "$file $label: MISSING_ANCHOR (markup changed? update tests/count-check.sh)"
  elif [ "$n" = "$expected" ]; then
    pass "$file $label = $n"
  else
    fail "$file $label = $n, expected $expected"
  fi
}

card assets/card-overview.html       Agents           "$N_AGENTS"
card assets/card-overview.html       Skills           "$N_SKILLS"
card assets/card-overview.html       Hooks            "$N_HOOKS"
card assets/card-overview.html       "Battle Stories" "$N_STORIES"

card assets/card-social-preview.html Agents           "$N_AGENTS"
card assets/card-social-preview.html Skills           "$N_SKILLS"
card assets/card-social-preview.html Hooks            "$N_HOOKS"
card assets/card-social-preview.html Rules            "$N_RULES"
card assets/card-social-preview.html "Battle Stories" "$N_STORIES"

card assets/walkthrough/slide-2.html Agents           "$N_AGENTS"
card assets/walkthrough/slide-2.html Skills           "$N_SKILLS"
card assets/walkthrough/slide-2.html Hooks            "$N_HOOKS"
card assets/walkthrough/slide-2.html "Battle Stories" "$N_STORIES"

bind assets/card-architecture.html '<div class="tag">([0-9]+) hooks across' "$N_HOOKS" "card-architecture hook tag"

echo ""
echo "=== Results ==="
echo "PASS: $PASS"
echo "FAIL: $FAIL"
echo ""

if [ $FAIL -gt 0 ]; then
  echo "Counts disagree with the filesystem, or a registered anchor no longer matches."
  echo "MISMATCH       update the document to the derived value."
  echo "MISSING_ANCHOR the document was reworded; update the binding in this script."
  exit 1
else
  echo "All registered counts match the filesystem."
  exit 0
fi
